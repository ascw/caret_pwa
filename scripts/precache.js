#!/usr/bin/env node
/*
Generates precache.js, which the service worker (sw.js) imports. It lists every
file needed to run Caret offline, plus a version hash computed from their
contents, so that any change to the app produces a new service worker.

Run `npm run build` (which compiles the CSS first) rather than calling this
directly, since css/*.css must exist before it can be cached.
*/

var fs = require("fs");
var path = require("path");
var crypto = require("crypto");

var root = path.resolve(__dirname, "..");

//only these top-level entries are part of the app
var include = [
  "index.html",
  "manifest.webmanifest",
  "require.js",
  "css",
  "config",
  "_locales",
  "js",
  "templates"
];
//icons live in the root
var iconPattern = /^icon-.*\.png$/;

//files that are in those directories but aren't needed by the running app
var skip = [/\.less$/, /\.rst$/, /\.md$/, /\.map$/, /(^|\/)\.[^/]+$/];

var files = [];

var walk = function(relative) {
  var absolute = path.join(root, relative);
  var stat = fs.statSync(absolute);
  if (stat.isDirectory()) {
    fs.readdirSync(absolute).sort().forEach(name => walk(path.posix.join(relative, name)));
  } else if (!skip.some(re => re.test(relative))) {
    files.push(relative);
  }
};

include.forEach(function(entry) {
  if (!fs.existsSync(path.join(root, entry))) {
    console.error("Missing " + entry + (entry == "css" ? " -- run the LESS build first (npm run build)" : ""));
    process.exit(1);
  }
  walk(entry);
});
fs.readdirSync(root).filter(name => iconPattern.test(name)).sort().forEach(name => files.push(name));

if (!files.some(f => /^css\/.+\.css$/.test(f))) {
  console.error("No compiled CSS found in css/. Run `grunt less` first (npm run build does this).");
  process.exit(1);
}

var hash = crypto.createHash("sha1");
files.forEach(function(file) {
  hash.update(file);
  hash.update(fs.readFileSync(path.join(root, file)));
});
var version = hash.digest("hex").slice(0, 12);

//"./" covers navigations to the bare URL
var list = ["./"].concat(files);

var output = [
  "// Generated by scripts/precache.js. Do not edit.",
  "self.CARET_VERSION = " + JSON.stringify(version) + ";",
  "self.CARET_PRECACHE = " + JSON.stringify(list, null, 2) + ";",
  ""
].join("\n");

fs.writeFileSync(path.join(root, "precache.js"), output);
console.log("precache.js: " + files.length + " files, version " + version);
