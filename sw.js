/*
Caret's service worker. It makes the app work offline and handles updates.

precache.js (generated by `npm run build`, see scripts/precache.js) lists every
file in the app and a version hash. When any file changes, the hash changes,
which makes this a new service worker; the new one downloads everything into a
fresh cache and then waits until the page asks it to take over (see main.js).

Anything not in the precache list (it shouldn't happen, but a development
checkout has no precache.js) is cached as it's fetched.
*/

try {
  importScripts("precache.js");
} catch (err) {
  self.CARET_VERSION = "dev";
  self.CARET_PRECACHE = [];
}

var CACHE_PREFIX = "caret-";
var CACHE = CACHE_PREFIX + self.CARET_VERSION;

self.addEventListener("install", function(event) {
  event.waitUntil(
    caches.open(CACHE).then(cache => cache.addAll(self.CARET_PRECACHE))
  );
});

self.addEventListener("activate", function(event) {
  event.waitUntil(
    caches.keys().then(function(keys) {
      return Promise.all(keys
        .filter(key => key.indexOf(CACHE_PREFIX) == 0 && key != CACHE)
        .map(key => caches.delete(key))
      );
    }).then(() => self.clients.claim())
  );
});

//the page tells us when the user has agreed to update
self.addEventListener("message", function(event) {
  if (event.data && event.data.type == "SKIP_WAITING") {
    self.skipWaiting();
  }
});

self.addEventListener("fetch", function(event) {
  var request = event.request;
  if (request.method != "GET") return;
  var url = new URL(request.url);
  if (url.origin != self.location.origin) return;

  event.respondWith(
    caches.open(CACHE).then(async function(cache) {
      //navigations to "/" or any other entry URL get the app shell
      var cached = await cache.match(request, { ignoreSearch: true });
      if (!cached && request.mode == "navigate") {
        cached = await cache.match("index.html");
      }
      if (cached) return cached;
      var response = await fetch(request);
      if (response.ok) cache.put(request, response.clone());
      return response;
    })
  );
});
